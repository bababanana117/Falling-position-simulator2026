"""Driver for the winter speed-distribution study.

Loads the winter analyses for one region and one cell, fits the speed model,
flies the scenarios and writes the tables and figures. Kept apart from the
one-off script it grew from so the appendix's numbers can be regenerated by a
command rather than by retyping.
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

from ..grid import bbox_slices
from ..regions import MASTER, REGIONS, BBox
from ..stats import windsample as ws
from ..stats.aggregate import AggregateConfig, load_window
from ..stats.drift import displacements
from ..timebins import SEASONS

__all__ = [
    "WinterStudy",
    "load_season_profiles",
    "run_winter_study",
    "terrain_box",
    "write_winter_tables",
]

log = logging.getLogger(__name__)

#: Samples per scenario. Enough that the scatter's shape is its own, not the
#: sampler's; the whole study runs in a few seconds at this size.
N_SAMPLES = 4000


class WinterStudy:
    """Everything the appendix quotes, in one object."""

    def __init__(self, region, season, model, clouds, u, v, levels, alt_m,
                 launch_lat=None, launch_lon=None):
        self.launch_lat = launch_lat
        self.launch_lon = launch_lon
        self.region = region
        self.season = season
        self.model = model
        self.clouds = clouds
        self.u = u
        self.v = v
        self.levels = levels
        self.alt_m = alt_m

    def spread_table(self) -> pd.DataFrame:
        rows = []
        for name, (dx, dy) in self.clouds.items():
            d = np.hypot(dx, dy)
            rows.append({
                "scenario": name,
                "east_sd_km": float(np.std(dx)),
                "north_sd_km": float(np.std(dy)),
                "dist_median_km": float(np.median(d)),
                "dist_p90_km": float(np.percentile(d, 90)),
                "n": int(dx.size),
            })
        return pd.DataFrame(rows)

    def fit_table(self) -> pd.DataFrame:
        return pd.DataFrame([{
            "level_hpa": f.level_hpa, "family": f.family, "ks": f.ks,
            "mean_ms": f.mean, "sd_ms": f.sd,
            "d_aic_norm": f.aic_norm - f.aic,
            "d_aic_weibull": f.aic_weibull - f.aic,
            "d_aic_uniform": f.aic_uniform - f.aic,
            "dir_sd_deg": float(self.model.dir_sd_deg[i]),
        } for i, f in enumerate(self.model.fits)])


def load_season_profiles(cache_root: Path, region: str, season: str, cfg: AggregateConfig):
    """Every analysis of one season at the region's centre cell, plus the altitudes."""
    months = SEASONS[season]
    us, vs = [], []
    lat = lon = None
    for year in cfg.years:
        for month in months:
            s = load_window(Path(cache_root), MASTER, year, month, cfg, extend_analyses=0)
            ys, xs = bbox_slices(s.lat, s.lon, REGIONS[region], strict=True)
            i = (ys.start + ys.stop) // 2
            j = (xs.start + xs.stop) // 2
            if lat is None:
                lat, lon = float(s.lat[i]), float(s.lon[j])
            us.append(s.u[:, :, i, j])
            vs.append(s.v[:, :, i, j])
            del s
    return np.concatenate(us).astype(float), np.concatenate(vs).astype(float), lat, lon


def run_winter_study(
    cache_root: Path, stats_path: Path, region: str, cfg: AggregateConfig,
    *, season: str | None = None, n: int = N_SAMPLES, seed: int = 1,
) -> WinterStudy:
    """Fit the speed model and fly every scenario."""
    season = season or next(iter(SEASONS))
    log.info("%s %s: loading profiles", region, season)
    u, v, lat, lon = load_season_profiles(cache_root, region, season, cfg)

    with xr.open_dataset(stats_path) as ds:
        alt = ds["alt_geom_mean_m"].sel(month=1, bin=1).isel(
            lat=ds.sizes["lat"] // 2, lon=ds.sizes["lon"] // 2
        ).values
    order = np.argsort(alt)
    alt_m = alt[order].astype(float)
    from ..config import kept_levels  # noqa: PLC0415

    levels = np.asarray(kept_levels())[order]
    u, v = u[:, order], v[:, order]

    log.info("%s %s: fitting %d levels from %d analyses", region, season, u.shape[1], u.shape[0])
    model = ws.fit_speeds(u, v, levels)
    flight = cfg.flight

    dxr, dyr = displacements(
        u[:, :, None, None], v[:, :, None, None], alt_m[:, None, None], flight
    )
    clouds = {"観測（実プロファイル）": (dxr[:, 0, 0] / 1000.0, dyr[:, 0, 0] / 1000.0)}

    sp_ind = ws.sample_speeds(model, n, correlated=False, seed=seed)
    clouds["風速のみ・層独立"] = ws.simulate_landings(
        sp_ind, model.mean_dir_deg, alt_m, flight
    )
    sp = ws.sample_speeds(model, n, correlated=True, seed=seed)
    clouds["風速のみ・鉛直相関あり"] = ws.simulate_landings(
        sp, model.mean_dir_deg, alt_m, flight
    )
    dirs = ws.sample_directions(model, n, correlated=True, seed=seed + 2)
    clouds["＋風向のばらつき"] = ws.simulate_landings(sp, dirs, alt_m, flight)
    a, b, c = ws.sample_flight_params(flight, ws.FlightSigma(), n, seed=seed + 1)
    clouds["＋機体（frontend 既定）"] = ws.simulate_landings(
        sp, dirs, alt_m, flight, ascent_ms=a, burst_m=b, descent_ms=c
    )
    return WinterStudy(region, season, model, clouds, u, v, levels, alt_m,
                       launch_lat=lat, launch_lon=lon)


def terrain_box(study: WinterStudy, *, margin_deg: float = 0.9) -> BBox:
    """A map box that holds every landing point with a margin.

    Derived from the clouds rather than hard-coded, so a different season or
    region gets a box that fits it instead of one that happens to suit winter
    in Wakayama.
    """
    km_lat = 111.195
    km_lon = 111.195 * float(np.cos(np.radians(study.launch_lat)))
    xs = np.concatenate([np.asarray(c[0]) for c in study.clouds.values()])
    ys = np.concatenate([np.asarray(c[1]) for c in study.clouds.values()])
    # Include the launch point itself. Every flight goes east, so the smallest
    # displacement is still well east of the star, and a box fitted to the
    # landings alone would crop the place they were launched from.
    xs = np.append(xs, 0.0)
    ys = np.append(ys, 0.0)
    return BBox(
        south=round(study.launch_lat + ys.min() / km_lat - margin_deg, 1),
        north=round(study.launch_lat + ys.max() / km_lat + margin_deg, 1),
        west=round(study.launch_lon + xs.min() / km_lon - margin_deg, 1),
        east=round(study.launch_lon + xs.max() / km_lon + margin_deg, 1),
    )


def write_winter_tables(study: WinterStudy, out_root: Path) -> list[Path]:
    folder = Path(out_root) / "csv"
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for name, frame in (("winter_spread", study.spread_table()),
                        ("winter_speed_fit", study.fit_table())):
        path = folder / f"{name}_{study.region}.csv"
        frame.to_csv(path, index=False, float_format="%.6g")
        written.append(path)
    return written
