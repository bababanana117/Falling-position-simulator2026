def main() -> int:
    out = HERE / "build" / "script.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    for s in SCENES:
        for line in s["lines"]:
            line.setdefault("say", line["text"])
    out.write_text(json.dumps(SCENES, ensure_ascii=False, indent=1), encoding="utf-8")
    n = sum(len(line["say"]) for s in SCENES for line in s["lines"])
    print(out, len(SCENES), "scenes,", n, "chars to read")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
